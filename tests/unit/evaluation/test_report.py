"""The published table has one row per configuration, marks the best, and shows failures.

A configuration that errors and disappears reads as one that was never tried.
"""

import json

from events_rag.evaluation import report
from events_rag.evaluation.report import render_table


def _result(name: str, recall: float | None = 0.8, error: str | None = None) -> dict:
    metrics = None if error else {"n": 20, "recall@1": 0.5, "recall@5": recall, "mrr@10": 0.6}
    return {
        "name": name,
        "variant": "baseline",
        "note": "a note",
        "metrics": metrics,
        "median_latency_ms": None if error else 12.5,
        "error": error,
    }


def test_table_has_one_row_per_configuration() -> None:
    table = render_table([_result("bm25-only"), _result("dense-baseline")])

    # Header, separator, then one row per configuration.
    assert len(table.splitlines()) == 4
    assert "bm25-only" in table
    assert "dense-baseline" in table


def test_failed_configuration_shows_its_error_rather_than_disappearing() -> None:
    table = render_table([_result("broken", error="RuntimeError: index missing")])

    assert "broken" in table
    assert "RuntimeError: index missing" in table


def test_best_recall_is_marked() -> None:
    table = render_table([_result("weak", recall=0.4), _result("strong", recall=0.9)])

    strong_row = next(line for line in table.splitlines() if "strong" in line)
    weak_row = next(line for line in table.splitlines() if "weak" in line)

    assert "**0.9**" in strong_row
    assert "**" not in weak_row.split("|")[4]


def test_the_run_writes_the_table_and_the_results_where_the_settings_say(
    tmp_path, monkeypatch
) -> None:
    """The two files the README reads. A run that wrote only one would half-publish."""

    questions = tmp_path / "questions"
    reports = tmp_path / "reports"
    questions.mkdir()
    (questions / "reference_qa.json").write_text(
        json.dumps([{"id": "q1", "question": "Un concert ?", "source_uid": "1"}]),
        encoding="utf-8",
    )

    settings = report.get_settings()
    monkeypatch.setattr(settings, "questions_dir", questions)
    monkeypatch.setattr(settings, "reports_dir", reports)
    monkeypatch.setattr(report, "run_all", lambda configs, cases: [_result("dense-baseline")])

    payload = report.run_ablation()

    written = json.loads((reports / "ablation_results.json").read_text(encoding="utf-8"))
    table = (reports / "ablation_table.md").read_text(encoding="utf-8")
    assert payload["configurations"] == 1
    assert written["results"][0]["name"] == "dense-baseline"
    assert "dense-baseline" in table
    assert "Generated by scripts/run_ablation.py" in table
