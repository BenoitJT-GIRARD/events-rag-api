"""Render the ablation results as the markdown table published in the README."""

import json
from datetime import date
from pathlib import Path

from events_rag.config import get_settings
from events_rag.evaluation.ablation import CONFIGS, run_all
from events_rag.evaluation.evaluate import load_reference_dataset

HEADER = "| Configuration | Chunking | recall@1 | recall@5 | MRR@10 | Median latency | Notes |"
SEPARATOR = "|---|---|---|---|---|---|---|"

#: The caption belongs to the script rather than to the file: written into the file, it would
#: disappear the next time `run_ablation.py` rewrote the table underneath it.
CAPTION = (
    "> **How to read it.** One row per retrieval configuration, every one of them answering the\n"
    "> same twenty questions. The recall columns ask whether the right event came back inside\n"
    "> the first k results, so they can only rise as k grows. MRR@10 (mean reciprocal rank over\n"
    "> ten results) averages one divided by the rank the right event reached, which separates\n"
    "> two configurations that both find it at different depths. The Notes column says what each\n"
    "> configuration changed.\n"
)


def render_table(results: list[dict]) -> str:
    best = max(
        (
            r["metrics"]["recall@5"]
            for r in results
            if r["metrics"] and r["metrics"]["recall@5"] is not None
        ),
        default=None,
    )

    lines = [HEADER, SEPARATOR]
    for result in results:
        if result["error"]:
            lines.append(
                f"| `{result['name']}` | {result['variant']} | — | — | — | — | "
                f"failed: {result['error']} |"
            )
            continue
        metrics = result["metrics"]
        recall5 = metrics["recall@5"]
        shown = f"**{recall5}**" if best is not None and recall5 == best else f"{recall5}"
        lines.append(
            f"| `{result['name']}` | {result['variant']} | {metrics['recall@1']} | {shown} | "
            f"{metrics['mrr@10']} | {result['median_latency_ms']} ms | {result['note']} |"
        )
    return "\n".join(lines)


def run_ablation() -> dict:
    settings = get_settings()
    reports_dir = Path(settings.reports_dir)
    cases = load_reference_dataset(Path(settings.questions_dir) / "reference_qa.json")
    results = run_all(CONFIGS, cases)

    payload = {"configurations": len(results), "results": results}
    reports_dir.mkdir(parents=True, exist_ok=True)
    # `newline=""` on every artefact this repository publishes: without it a run on Windows
    # writes CRLF where a run on Linux writes LF, and the comparison that proves the
    # published file is the file the code produces then fails on every line.
    (reports_dir / "ablation_results.json").write_text(
        json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8", newline=""
    )
    header = (
        f"<!-- Generated by scripts/run_ablation.py on {date.today().isoformat()}. "
        "Edit the run, not this file. -->\n\n"
    )
    (reports_dir / "ablation_table.md").write_text(
        header + render_table(results) + "\n\n" + CAPTION, encoding="utf-8", newline=""
    )
    return payload
